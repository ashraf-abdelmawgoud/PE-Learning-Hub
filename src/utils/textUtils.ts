/**
 * معالجة وتوحيد النصوص العربية لتحسين دقة البحث
 * يشمل: توحيد الهمزات، التاء المربوطة، الألف المقصورة، تحويل الأرقام العربية-الهندية، وإزالة علامات التشكيل.
 */
export function normalizeArabicText(text: string): string {
  if (!text) return '';

  return text
    // تحويل الأرقام المشرقية (١، ٢، ...) إلى أرقام قياسية (1, 2, ...)
    .replace(/[٠-٩]/g, (digit) => '٠١٢٣٤٥٦٧٨٩'.indexOf(digit).toString())
    // إزالة التشكيل وعلامات الإعراب
    .replace(/[\u064B-\u065F\u0670]/g, '')
    // توحيد الألف بكافة أشكالها (أ، إ، آ، ٱ) إلى (ا)
    .replace(/[أإآٱ]/g, 'ا')
    // توحيد التاء المربوطة والهاء في نهايات الكلمات للبحث المرن
    .replace(/ة/g, 'ه')
    // توحيد الألف المقصورة (ى) إلى ياء (ي)
    .replace(/ى/g, 'ي')
    .toLowerCase()
    .trim();
}

